<section class="section legal-content">
    <h1>Politique de confidentialité</h1>

    <h2>Données collectées</h2>
    <p>
        Vite & Gourmand collecte les données nécessaires à la création du
        compte, à la livraison, au suivi des commandes et au traitement des
        demandes de contact.
    </p>

    <h2>Finalités et base légale</h2>
    <p>
        Les informations de commande sont traitées pour exécuter le contrat.
        Les données de compte et de contact sont utilisées pour fournir le
        service demandé et sécuriser l’accès à l’application.
    </p>

    <h2>Durée de conservation</h2>
    <ul>
        <li>commandes et facturation : durée imposée par les obligations légales ;</li>
        <li>compte client : durée de la relation, puis archivage ou suppression ;</li>
        <li>demandes de contact : temps nécessaire à leur traitement ;</li>
        <li>jetons de réinitialisation : une heure, puis invalidation.</li>
    </ul>

    <h2>Destinataires</h2>
    <p>
        Seuls les employés habilités accèdent aux informations indispensables
        au traitement des commandes. Les mots de passe ne sont jamais stockés
        en clair.
    </p>
    <p>
        Les données sont hébergées par alwaysdata pour l’application et la base
        relationnelle, et par MongoDB Atlas pour les avis et statistiques.
    </p>

    <h2>Cookies</h2>
    <p>
        L’application utilise uniquement un cookie de session nécessaire à
        l’authentification et à la protection CSRF. Aucun outil publicitaire ou
        de suivi comportemental n’est intégré.
    </p>

    <h2>Vos droits</h2>
    <p>
        Vous pouvez demander l’accès, la rectification ou l’effacement de vos
        données, ainsi que la limitation ou l’opposition lorsque ces droits
        s’appliquent, en écrivant à
        <a href="mailto:<?= htmlspecialchars($companyEmail, ENT_QUOTES) ?>">
            <?= htmlspecialchars($companyEmail) ?>
        </a>. Vous pouvez également adresser une réclamation à la CNIL.
    </p>
